/*==================== APPLY LANGUAGE ====================*/
function applyLanguage(lang) {
  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    const value = translations[lang][key];
    if (value) el.textContent = value;
  });

  document.querySelectorAll("[data-i18n-html]").forEach((el) => {
    const key = el.getAttribute("data-i18n-html");
    const value = translations[lang][key];
    if (value) el.innerHTML = value;
  });

  document.documentElement.setAttribute("lang", lang === "pt" ? "pt-BR" : "en");

  const langToggle = document.getElementById("lang-toggle");
  if (langToggle) langToggle.textContent = lang === "pt" ? "EN" : "PT";

  localStorage.setItem("selected-lang", lang);
}

const langToggle = document.getElementById("lang-toggle");
const savedLang = localStorage.getItem("selected-lang");
const browserLang = navigator.language && navigator.language.toLowerCase().startsWith("pt") ? "pt" : "en";
let currentLang = savedLang || browserLang;

applyLanguage(currentLang);

if (langToggle) {
  langToggle.addEventListener("click", () => {
    currentLang = currentLang === "pt" ? "en" : "pt";
    applyLanguage(currentLang);
  });
}
